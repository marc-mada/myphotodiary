-- Video transcoding (27/10/2026, explicit ask - "option C"): any video
-- ffmpeg can read is accepted; the original is kept as uploaded and, when a
-- browser can't be relied on to play it (HEVC, AVI, DV, 4K, 60 fps...), an
-- H.264 copy (at most 1080p, 30 fps) is made in the background for
-- playback. Optionally (app-wide setting, off by default) an original in an
-- inefficient codec (ProRes, DV, MJPEG, MPEG-2...) is re-encoded to HEVC.
--
-- image.video_playback: which file plays a video - ORIGINAL (or NULL, every
-- video stored before this migration), PENDING (copy not made yet), COPY,
-- FAILED. NULL for a picture.
--
-- video_job: the background queue. priority 0 = playback copy, 1 = original
-- compaction, so every waiting copy runs before any compaction. A job is
-- deleted when it succeeds; FAILED ones stay for the Admin count.
-- Portable SQL (HSQLDB/PostgreSQL).
ALTER TABLE image ADD COLUMN video_playback VARCHAR(20);

ALTER TABLE app_settings ADD COLUMN compact_original_videos BOOLEAN DEFAULT FALSE NOT NULL;

CREATE TABLE video_job (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id   BIGINT        NOT NULL REFERENCES image (id) ON DELETE CASCADE,
    stage      VARCHAR(30)   NOT NULL,
    priority   INTEGER       NOT NULL,
    state      VARCHAR(20)   NOT NULL,
    attempts   INTEGER       DEFAULT 0 NOT NULL,
    last_error VARCHAR(1000),
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP     NOT NULL
);

CREATE INDEX video_job_queue ON video_job (state, priority, id);
